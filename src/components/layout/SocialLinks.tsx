/* 페이지에 한 번만 렌더링되는 푸터이므로 그라데이션 id를 고정해도 충돌하지 않습니다. */
const INSTAGRAM_GRADIENT_ID = "hg-social-instagram-gradient";

/**
 * 플랫폼별 브랜드 컬러 글리프.
 *
 * - YouTube·Facebook: currentColor(= CSS의 --brand)로 단색 채움
 * - Instagram: 공식 그라데이션(주황→핑크→보라→파랑)
 * - TikTok: 시안/마젠타를 좌우로 아주 살짝 어긋나게 깔아 로고 특유의 색 번짐을 표현
 */
function SocialGlyph({ platform }: { platform: SocialPlatform }) {
  const d = ICON_PATH[platform];

  if (platform === "Instagram") {
    return (
      <>
        <defs>
          <linearGradient
            id={INSTAGRAM_GRADIENT_ID}
            x1="0"
            y1="1"
            x2="1"
            y2="0"
          >
            <stop offset="0%" stopColor="#f58529" />
            <stop offset="30%" stopColor="#dd2a7b" />
            <stop offset="65%" stopColor="#8134af" />
            <stop offset="100%" stopColor="#515bd4" />
          </linearGradient>
        </defs>
        <path d={d} fill={`url(#${INSTAGRAM_GRADIENT_ID})`} />
      </>
    );
  }

  if (platform === "TikTok") {
    return (
      <g>
        <path d={d} fill="#25f4ee" transform="translate(-0.7 0)" />
        <path d={d} fill="#fe2c55" transform="translate(0.7 0)" />
        <path d={d} fill="#161823" />
      </g>
    );
  }

  return <path d={d} />;
}

